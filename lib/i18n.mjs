const germanToPolish = new Map(
 rows.split("\n").map(row=>{
  const split=row.indexOf("\t");
  return [row.slice(0,split),row.slice(split+1)];
 })
);

// German text can have UI emoji and arrows as prefixes without changing its meaning.
const prefixPattern = /^((?:[\s\p{Extended_Pictographic}\uFE0F\u200D\u2640\u2642\u{1F1E6}-\u{1F1FF}✨⭐🔥🖌️✂️🎨🧩🎁🎲↗️←‹＋+\-–✓⚫🌈🎨🔐⏱️⚙️🖨️❓ℹ️🗑️↺🔊💾👧🎭🌀🔎🔍🏆])+)(.+)$/u;

const replacements = [
 [/^(\d+) Jahre$/,(_,n)=>n+" lat"],
 [/^(\d+) Tage Serie$/,(_,n)=>n+" dni serii"],
 [/^(\d+) Teile$/,(_,n)=>n+" elementów"],
 [/^(\d+) Unterschiede$/,(_,n)=>n+" różnic"],
 [/^(\d+) Bilder$/,(_,n)=>n+" obrazków"],
 [/^(\d+) von (\d+) gefunden$/,(_,a,b)=>a+" z "+b+" znalezionych"],
 [/^Finde (\d+) Unterschiede$/,(_,n)=>"Znajdź "+n+" różnic"],
 [/^(\d+) Sterne$/,(_,n)=>n+" gwiazdek"],
 [/^(\d+) Minuten?$/,(_,n)=>n+" minut"],
 [/^(\d+) Min\.$/,(_,n)=>n+" min"],
 [/^(\d+) Rätsel gelöst$/,(_,n)=>n+" rozwiązanych zagadek"],
 [/^Kinderprofil (\d+)$/,(_,n)=>"Profil dziecka "+n]
];

export function translateGerman(value,language="pl"){
 if(language!=="pl"||typeof value!=="string")return value;
 if(germanToPolish.has(value))return germanToPolish.get(value);
 const match=value.match(/^(\s*)(.*?)(\s*)$/s);
 if(!match)return value;
 const [,leading,core,trailing]=match;
 if(!core)return value;
 if(germanToPolish.has(core))return leading+germanToPolish.get(core)+trailing;
 for(const [pattern,render] of replacements)if(pattern.test(core))return leading+core.replace(pattern,render)+trailing;
 const suffix=core.match(/^(.+?)(\s+[\p{Extended_Pictographic}\uFE0F\u200D]+)$/u);
 if(suffix){
  const translated=translateGerman(suffix[1],language);
  if(translated!==suffix[1])return leading+translated+suffix[2]+trailing;
 }
 const prefix=core.match(prefixPattern);
 if(prefix){
  const original=prefix[2];
  const translated=translateGerman(original,language);
  if(original!==translated)return leading+prefix[1]+translated+trailing;
 }
 // Sometimes buttons contain only a trailing arrow or exclamation mark.
 const tail=core.match(/^(.+?)(\s*[›↓])$/);
 if(tail){
  const translated=translateGerman(tail[1],language);
  if(translated!==tail[1])return leading+translated+tail[2]+trailing;
 }
 return value;
}

/** DOM originals are retained when switching back to German. */
const textCache=new WeakMap();
const attrCache=new WeakMap();
const attributes=["placeholder","aria-label","title","alt"];

function eligible(element){
 return element && !element.closest?.("[data-i18n-ignore],script,style,code,pre,[contenteditable]");
}

function localizeText(node,language){
 const parent=node.parentElement;
 if(!eligible(parent)||parent.closest?.("input,textarea"))return;
 const current=node.nodeValue;
 const prior=textCache.get(node);
 const original=prior && prior.rendered===current ? prior.original : current;
 const rendered=translateGerman(original,language);
 textCache.set(node,{original,rendered});
 if(current!==rendered)node.nodeValue=rendered;
}
function localizeAttributes(element,language){
 if(!eligible(element))return;
 let originals=attrCache.get(element);
 if(!originals){originals=new Map();attrCache.set(element,originals)}
 for(const name of attributes){
  if(!element.hasAttribute(name))continue;
  const current=element.getAttribute(name);
  const prior=originals.get(name);
  const original=prior && prior.rendered===current?prior.original:current;
  const rendered=translateGerman(original,language);
  originals.set(name,{original,rendered});
  if(current!==rendered)element.setAttribute(name,rendered);
 }
}
function scan(node,language){
 if(node.nodeType===3){localizeText(node,language);return}
 if(node.nodeType!==1)return;
 if(!eligible(node))return;
 localizeAttributes(node,language);
 for(const child of Array.from(node.childNodes))scan(child,language);
}

/**
 * Translates React-rendered UI without mutating the application's canonical
 * German data structures, saved profiles, puzzle IDs or user-generated names.
 * Covers dynamically mounted dialogs, screens, quiz text and accessibility labels.
 */
export function installUiTranslation(root,language){
 if(!root)return ()=>{};
 const doc=root.ownerDocument;
 const MutationObserver=doc.defaultView?.MutationObserver;
 scan(root,language);
 if(!MutationObserver)return ()=>{};
 const observer=new MutationObserver(mutations=>{
  for(const mutation of mutations){
   if(mutation.type==="characterData")scan(mutation.target,language);
   else if(mutation.type==="attributes")localizeAttributes(mutation.target,language);
   else if(mutation.type==="childList"){
    for(const child of mutation.addedNodes)scan(child,language);
   }
  }
 });
 observer.observe(root,{subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:attributes});
 return ()=>observer.disconnect();
}

