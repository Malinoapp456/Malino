function shuffle(values,random){
 const result=[...values];
 for(let i=result.length-1;i>0;i--){
  const j=Math.floor(random()*(i+1));
  [result[i],result[j]]=[result[j],result[i]];
 }
 return result;
}

export function makeRounds(random=Math.random){
 const ids=Object.keys(animals);
 return shuffle(ids,random).map((target,index)=>{
  const others=shuffle(ids.filter(id=>id!==target),random);
  return {target,choices:shuffle([target,...others.slice(0,index<2?1:2)],random)};
 });
}
